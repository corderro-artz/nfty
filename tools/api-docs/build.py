def write_tree(files, dest):
    if os.path.isdir(dest):
        shutil.rmtree(dest)
    for rel, text in files.items():
        path = os.path.join(dest, *rel.split('/'))
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, 'w', encoding='utf-8', newline='\n') as f:
            f.write(text)


def read_tree(root):
    found = {}
    for base, _, names in os.walk(root):
        for n in names:
            full = os.path.join(base, n)
            rel = os.path.relpath(full, root).replace(os.sep, '/')
            with open(full, 'r', encoding='utf-8', newline='') as f:
                found[rel] = f.read()
    return found


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--check', action='store_true',
                    help='regenerate to a temporary folder and compare; exit 1 when the committed pages differ')
    ap.add_argument('--lint', action='store_true',
                    help='check the documentation itself (blank or name-only summaries, missing param, '
                         'typeparam and returns, unresolved cref); exit 1 listing every offender')
    ap.add_argument('--surface', metavar='FILE',
                    help='use a saved surface dump (the JSON the surface tool prints) instead of running dotnet')
    args = ap.parse_args()

    if args.surface:
        with open(args.surface, encoding='utf-8') as f:
            surface = json.load(f)
    else:
        surface = run_surface()
    if args.lint:
        found = lint(surface)
        if found:
            print(f'api-docs: {len(found)} documentation problem(s) in the public surface:\n')
            print('\n'.join(found))
            return 1
        print('api-docs: documentation lint clean')
        return 0
    files = generate(surface)

    if not args.check:
        write_tree(files, OUT)
        print(f'api-docs: wrote {len(files)} pages to {os.path.relpath(OUT, ROOT)}')
        return 0

    committed = read_tree(OUT) if os.path.isdir(OUT) else {}
    problems = []
    for rel in sorted(set(files) | set(committed)):
        if rel not in committed:
            problems.append(f'missing  {rel}')
        elif rel not in files:
            problems.append(f'stale    {rel}')
        elif committed[rel] != files[rel]:
            diff = difflib.unified_diff(committed[rel].splitlines(), files[rel].splitlines(),
                                        'committed/' + rel, 'generated/' + rel, lineterm='', n=1)
            problems.append(f'differs  {rel}\n' + '\n'.join(list(diff)[:12]))
    if problems:
        print('api-docs: the committed API pages are out of date with the code.\n')
        print('\n'.join(problems[:30]))
        if len(problems) > 30:
            print(f'... and {len(problems) - 30} more')
        print('\nRun `python tools/api-docs/build.py` and commit the result.')
        return 1
    print(f'api-docs: {len(files)} pages up to date')
    return 0


if __name__ == '__main__':
    sys.exit(main())
