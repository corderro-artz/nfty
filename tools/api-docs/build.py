def run_surface():
    """Builds the libraries and the surface tool, runs it, returns the parsed JSON."""
    # Built first, on its own: `dotnet run` prints restore and build chatter on stdout when it has to
    # build, and stdout is where the JSON comes back.
    build = subprocess.run(['dotnet', 'build', SURFACE_PROJECT, '-c', 'Release', '--nologo', '-v', 'q'],
                           cwd=ROOT, capture_output=True, text=True, encoding='utf-8')
    if build.returncode != 0:
        sys.stderr.write(build.stdout + build.stderr)
        sys.exit('api-docs: building the libraries or the surface tool failed (see above).')
    proc = subprocess.run(['dotnet', 'run', '--no-build', '--project', SURFACE_PROJECT, '-c', 'Release'],
                          cwd=ROOT, capture_output=True, text=True, encoding='utf-8')
    if proc.returncode != 0:
        sys.stderr.write(proc.stdout + proc.stderr)
        sys.exit('api-docs: the surface tool failed (see above).')
    return json.loads(proc.stdout)


def load_docs(assembly):
    """The XML doc file for an assembly as {id: element}."""
    path = os.path.join(ROOT, 'src', assembly, 'bin', 'Release', 'net10.0', assembly + '.xml')
    if not os.path.exists(path):
        sys.exit(f'api-docs: {path} is missing. Run `dotnet build src/{assembly} -c Release` first '
                 '(running this script without --surface does it for you).')
    docs = {}
    for m in ET.parse(path).getroot().iter('member'):
        docs[m.get('name')] = m
    return docs


