"""Generates the API reference pages under docs/manual/reference/api/ from the libraries' XML docs.

Two inputs, joined on the XML documentation id (`M:Ns.Type.Method(System.String)`):

  * the compiler's `bin/Release/net10.0/<Assembly>.xml` - every word of prose (summary, remarks,
    params, returns, exceptions, examples), written next to the code it describes;
  * `tools/api-docs/surface`, a small console program that reads the built assemblies and prints
    their PUBLIC surface as JSON. The XML cannot supply this: it lists internal and private members
    too, and it carries no return types, modifiers, nullability or default values.

The pages are COMMITTED, like Icons.axaml: the manual is built by the site repository, which must not
need a .NET SDK. Edit a `///` comment, run this, commit the pages - `--check` fails CI when the two
disagree, so the generated half cannot quietly become the real one.

    python tools/api-docs/build.py                 # rebuild the libraries, regenerate the pages
    python tools/api-docs/build.py --check         # regenerate to a temp folder, diff, exit 1 on drift
    python tools/api-docs/build.py --lint          # complain about thin or broken documentation, exit 1
    python tools/api-docs/build.py --surface s.json   # reuse a surface dump instead of running dotnet

Only the standard library is used. Output is deterministic: ordinal sorts, LF line endings, no
timestamps and no versions, so an unchanged API produces byte-identical files on any machine.
"""
