# Resolving a member's documentation (inheritdoc included)
# ------------------------------------------------------------------------------------------------

SECTION_TAGS = ('summary', 'remarks', 'returns', 'value', 'example')


def sections(model, doc_id, member=None, seen=None):
    """{'summary': el, ..., 'param': {name: el}, 'typeparam': {...}, 'exception': [el]} for an id."""
    seen = seen or set()
    if doc_id in seen:
        return {}
    seen = seen | {doc_id}
    el = model.docs.get(doc_id)
    result = {'param': {}, 'typeparam': {}, 'exception': [], 'seealso': []}
    if el is None and not (member and member.get('inherits')):
        return result
    own = {'param': {}, 'typeparam': {}, 'exception': [], 'seealso': []}
    inherit_el = None
    if el is not None:
        for child in el:
            if child.tag in SECTION_TAGS:
                own[child.tag] = child
            elif child.tag == 'param':
                own['param'][child.get('name')] = child
            elif child.tag == 'typeparam':
                own['typeparam'][child.get('name')] = child
            elif child.tag == 'exception':
                own['exception'].append(child)
            elif child.tag == 'seealso':
                own['seealso'].append(child)
            elif child.tag == 'inheritdoc':
                inherit_el = child

    wants_inherit = inherit_el is not None
    if wants_inherit:
        targets = [inherit_el.get('cref')] if inherit_el.get('cref') else list((member or {}).get('inherits', []))
        path = (inherit_el.get('path') or '').strip('/ ')
        for target in targets:
            tmember = model.members.get(target, (None, None))[1]
            inherited = sections(model, target, tmember, seen)
            if not any(inherited.get(k) is not None for k in SECTION_TAGS) and not inherited.get('param'):
                continue
            if path:
                tag = path.split('[')[0]
                if tag in SECTION_TAGS and inherited.get(tag) is not None:
                    result[tag] = inherited[tag]
            else:
                for k in SECTION_TAGS:
                    if inherited.get(k) is not None:
                        result[k] = inherited[k]
                result['param'].update(inherited['param'])
                result['typeparam'].update(inherited['typeparam'])
                result['exception'].extend(inherited['exception'])
            break
    for k in SECTION_TAGS:
        if own.get(k) is not None:
            result[k] = own[k]
    result['param'].update(own['param'])
    result['typeparam'].update(own['typeparam'])
    result['exception'] = own['exception'] + [e for e in result['exception'] if e not in own['exception']]
    # A block-level <seealso> is a reference list, so it is the member's own and never inherited.
    result['seealso'] = own['seealso']
    return result


def first_sentence(text):
    """The first sentence of a rendered summary, for index tables (backtick-aware)."""
    in_code = False
    for i, ch in enumerate(text):
        if ch == '`':
            in_code = not in_code
        elif ch == '.' and not in_code and (i + 1 == len(text) or text[i + 1] == ' '):
            return text[:i + 1]
    return text


def table_cell(text):
    return text.replace('|', '\\|').replace('\n', ' ')


