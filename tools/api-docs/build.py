def see_also(r, s):
    """The 'See also' list for a member or type: every block-level <seealso> it carries."""
    items = [r.inline_el(e) for e in s.get('seealso', [])]
    items = [i for i in items if i]
    return ['**See also**', ''] + ['- ' + i for i in items] + [''] if items else []


def render_member(model, r, tid, m):
    s = sections(model, m['id'], m)
    if m['kind'] == 'constructor':
        # A record's constructor repeats the type's summary word for word; saying it twice is noise.
        own = sections(model, tid).get('summary')
        if own is not None and s.get('summary') is not None                 and r.blocks(own) == r.blocks(s['summary']):
            s['summary'] = None
    out = [f"### {esc_heading(m['display'])} {{ #{m['anchor']} }}", '',
           '```csharp', m['signature'] + ('' if m['kind'] == 'property' else ';'), '```', '']
    if s.get('summary') is not None:
        b = r.blocks(s['summary'])
        if b:
            out += [b, '']
    if s.get('value') is not None and r.blocks(s['value']):
        out += ['**Value.** ' + r.blocks(s['value']), '']
    ptypes = {p['name']: p['type'] for p in m.get('params', [])}
    if m.get('params'):
        out += ['**Parameters**', '']
        for p in m['params']:
            d = s['param'].get(p['name'])
            text = r.collapse(r.inline(d)) if d is not None else ''
            out.append(f"- `{p['name']}` (`{p['type']}`)" + (f' - {text}' if text else ''))
        out.append('')
    tps = {k: v for k, v in s['typeparam'].items()}
    if tps:
        out += ['**Type parameters**', '']
        for k in sorted(tps):
            out.append(f"- `{k}`" + (f' - {r.collapse(r.inline(tps[k]))}' if tps[k] is not None else ''))
        out.append('')
    if s.get('returns') is not None and r.blocks(s['returns']):
        out += ['**Returns.** ' + r.blocks(s['returns']), '']
    if s['exception']:
        out += ['**Exceptions**', '']
        for e in s['exception']:
            out.append(f"- {r.cref(e.get('cref'))} - {r.collapse(r.inline(e))}")
        out.append('')
    if s.get('remarks') is not None:
        b = r.blocks(s['remarks'])
        if b:
            out += ['**Remarks**', '', b, '']
    if s.get('example') is not None:
        b = r.blocks(s['example'])
        if b:
            out += ['**Example**', '', b, '']
    out += see_also(r, s)
    return out


def render_type(model, t):
    page = f"{ASSEMBLIES[t['assembly']][0]}/{type_file(t)}"
    r = Renderer(model, page)
    s = sections(model, t['id'])
    out = [GENERATED, '', f"# {esc_heading(t['name'])}", '',
           f"Namespace `{t['namespace']}` in assembly `{t['assembly']}`.", '',
           '```csharp', t['declaration'], '```', '']
    if s.get('summary') is not None:
        b = r.blocks(s['summary'])
        if b:
            out += [b, '']
    tps = s['typeparam']
    if tps:
        out += ['**Type parameters**', '']
        for k in sorted(tps):
            out.append(f"- `{k}` - {r.collapse(r.inline(tps[k]))}")
        out.append('')
    for tag, title in (('remarks', 'Remarks'), ('example', 'Example')):
        if s.get(tag) is not None:
            b = r.blocks(s[tag])
            if b:
                out += [f'## {title}', '', b, '']
    sa = see_also(r, s)
    if sa:
        out += ['## See also', ''] + sa[2:]

    members = t.get('members', [])
    if t['kind'] == 'enum':
        if members:
            out += ['## Values', '']
            for m in members:
                d = sections(model, m['id'], m).get('summary')
                text = r.collapse(r.inline(d)) if d is not None else ''
                out.append(f"- <span id=\"{m['anchor']}\"></span>`{m['signature']}`" + (f' - {text}' if text else ''))
            out.append('')
    else:
        for kind, title in KIND_TITLES:
            group = sorted((m for m in members if m['kind'] == kind),
                           key=lambda m: (m['display'].split('(')[0], m['display']))
            if not group:
                continue
            out += [f'## {title}', '']
            for m in group:
                out += render_member(model, r, t['id'], m)
    return page, '\n'.join(out).rstrip() + '\n'


def summary_text(model, t, page):
    r = Renderer(model, page)
    s = sections(model, t['id']).get('summary')
    return first_sentence(r.collapse(r.blocks(s))) if s is not None else ''


def render_assembly_index(model, asm, types):
    folder, blurb = ASSEMBLIES[asm]
    page = f'{folder}/index.md'
    out = [GENERATED, '', f'# {asm}', '', blurb, '',
           f'{len(types)} public types. Each page lists the public and protected members with their '
           'signatures and the documentation written beside the code.', '']
    by_ns = {}
    for t in types:
        by_ns.setdefault(t['namespace'], []).append(t)
    for ns in sorted(by_ns, key=lambda n: n):
        out += [f'## {ns}', '', '| Type | Kind | Summary |', '|---|---|---|']
        for t in sorted(by_ns[ns], key=lambda t: t['name']):
            link = f"[`{t['name']}`]({type_file(t)})"
            out.append(f"| {link} | {t['kind']} | {table_cell(summary_text(model, t, f'{folder}/{type_file(t)}'))} |")
        out.append('')
    return page, '\n'.join(out).rstrip() + '\n'


