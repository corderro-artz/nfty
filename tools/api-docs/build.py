def esc(text):
    """Escapes prose for Markdown: angle brackets, emphasis and link characters."""
    text = text.replace('\\', '\\\\')
    for ch in '`*[]':
        text = text.replace(ch, '\\' + ch)
    return text.replace('<', '&lt;').replace('>', '&gt;')


def esc_heading(text):
    return text.replace('<', '&lt;').replace('>', '&gt;').replace('*', '\\*').replace('[', '\\[')


def short_name_of_cref(cref):
    body = cref[2:] if len(cref) > 1 and cref[1] == ':' else cref
    body = body.split('(')[0]
    body = re.sub(r'\{.*\}', '', body)
    return body.split('.')[-1].split('`')[0] or body


class Renderer:
    def __init__(self, model, page):
        self.model = model
        self.page = page          # forward-slash path of the page being written, relative to api/

    def link_to(self, target):
        return relpath(target, dirname(self.page) or '.').replace('\\', '/')

    def cref(self, cref, text=None):
        """A link to a documented symbol, or its plain name when it is not one of ours."""
        if not cref:
            return esc(text or '')
        model = self.model
        kind = cref[0] if len(cref) > 1 and cref[1] == ':' else ''
        if cref in model.types:
            t = model.types[cref]
            label = text or t['name']
            return f"[`{label}`]({self.link_to(model.page_of(cref))})"
        if cref in model.members:
            tid, m = model.members[cref][0], model.members[cref][1]
            owner = model.types[tid]['name']
            label = text or (owner + '.' + m['display'].split('(')[0] + ('()' if m['kind'] in ('method', 'constructor') else ''))
            return f"[`{label}`]({self.link_to(model.page_of(tid))}#{m['anchor']})"
        label = text or short_name_of_cref(cref)
        if kind == 'M' and not text:
            label += '()'
        return f'`{label}`'

    # -- inline ------------------------------------------------------------------------------------
    def inline(self, el):
        parts = []
        if el.text:
            parts.append(esc(el.text))
        for child in el:
            parts.append(self.inline_el(child))
            if child.tail:
                parts.append(esc(child.tail))
        return ''.join(parts)

    def inline_el(self, el):
        tag = el.tag
        text = ''.join(el.itertext()).strip()
        if tag in ('see', 'seealso'):
            if el.get('cref'):
                return self.cref(el.get('cref'), text or None)
            if el.get('langword'):
                return f"`{el.get('langword')}`"
            if el.get('href'):
                return f"[{esc(text) or esc(el.get('href'))}]({el.get('href')})"
            return esc(text)
        if tag == 'a':
            return f"[{esc(text)}]({el.get('href', '')})"
        if tag == 'c':
            return '`' + text.replace('`', "'") + '`'
        if tag in ('b', 'strong'):
            return '**' + self.inline(el).strip() + '**'
        if tag in ('i', 'em'):
            return '*' + self.inline(el).strip() + '*'
        if tag in ('paramref', 'typeparamref'):
            return f"`{el.get('name', '')}`"
        if tag == 'br':
            return '  \n'
        return self.inline(el)

    @staticmethod
    def collapse(text):
        return re.sub(r'[ \t\r\n]+', ' ', text).strip()

    # -- blocks ------------------------------------------------------------------------------------
    def blocks(self, el):
        """Markdown for an element whose content may mix prose, <para>, <list> and <code>."""
        out = []
        run = []

        def flush():
            s = self.collapse(''.join(run))
            run.clear()
            if s:
                out.append(s)

        if el.text:
            run.append(esc(el.text))
        for child in el:
            if child.tag == 'para':
                flush()
                inner = self.blocks(child)
                if inner:
                    out.append(inner)
            elif child.tag == 'code':
                flush()
                out.append(self.code_block(child))
            elif child.tag == 'list':
                flush()
                out.append(self.list_block(child))
            elif child.tag == 'inheritdoc':
                pass
            else:
                run.append(self.inline_el(child))
            if child.tail:
                run.append(esc(child.tail))
        flush()
        return '\n\n'.join(out)

    @staticmethod
    def code_block(el):
        raw = ''.join(el.itertext()).replace('\r\n', '\n')
        lines = raw.split('\n')
        while lines and not lines[0].strip():
            lines.pop(0)
        while lines and not lines[-1].strip():
            lines.pop()
        indent = min((len(l) - len(l.lstrip()) for l in lines if l.strip()), default=0)
        body = '\n'.join(l[indent:].rstrip() for l in lines)
        lang = el.get('lang') or 'csharp'
        return f'```{lang}\n{body}\n```'

    def list_block(self, el):
        kind = el.get('type', 'bullet')
        items = []
        for i, item in enumerate(el.findall('item'), 1):
            term = item.find('term')
            desc = item.find('description')
            if term is not None and desc is not None:
                text = f"**{self.collapse(self.inline(term))}** - {self.collapse(self.inline(desc))}"
            elif desc is not None:
                text = self.collapse(self.inline(desc))
            elif term is not None:
                text = self.collapse(self.inline(term))
            else:
                text = self.collapse(self.inline(item))
            items.append((f'{i}. ' if kind == 'number' else '- ') + text)
        return '\n'.join(items)


