def slug(text):
    return re.sub(r'[^a-z0-9]+', '-', text.lower()).strip('-')


def type_file(t):
    """Page file name of a type: the full name, generic ticks made filename-safe."""
    full = t['id'][2:]
    return re.sub(r'[^A-Za-z0-9._]', '-', full) + '.md'


def member_anchor(type_id, m):
    rest = m['id'][2:]
    prefix = type_id[2:] + '.'
    if rest.startswith(prefix):
        rest = rest[len(prefix):]
    a = m['id'][0].lower() + '-' + slug(rest)
    if len(a) > 64:
        a = a[:56].rstrip('-') + '-' + hashlib.sha1(m['id'].encode('utf-8')).hexdigest()[:6]
    return a


class Model:
    def __init__(self, surface):
        self.types = {}      # type id -> (assembly, type dict)
        self.members = {}    # member id -> (type id, member dict, anchor)
        self.docs = {}
        for asm in surface:
            name = asm['assembly']
            self.docs.update(load_docs(name))
            for t in asm['types']:
                t['assembly'] = name
                self.types[t['id']] = t
                for m in t.get('members', []):
                    m['anchor'] = member_anchor(t['id'], m)
                    self.members[m['id']] = (t['id'], m)

    def page_of(self, type_id):
        t = self.types[type_id]
        return f"{ASSEMBLIES[t['assembly']][0]}/{type_file(t)}"


